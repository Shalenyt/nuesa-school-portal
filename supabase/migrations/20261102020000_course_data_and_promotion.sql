-- 9. End-of-session promotion (admin only)
CREATE OR REPLACE FUNCTION public.promote_students(p_student_ids uuid[])
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_count integer := 0;
  r record;
  v_next uuid;
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'Only admins can promote students';
  END IF;

  FOR r IN
    SELECT p.id, p.department_id, substring(c.name from '\d{3}')::int AS lvl
    FROM public.profiles p
    JOIN public.classes c ON c.id = p.level_id
    WHERE p.id = ANY(p_student_ids) AND p.role = 'student' AND p.status = 'approved'
  LOOP
    -- 500 level is final year: nothing to move to
    SELECT id INTO v_next FROM public.classes
    WHERE substring(name from '\d{3}')::int = r.lvl + 100
    LIMIT 1;
    CONTINUE WHEN v_next IS NULL;

    UPDATE public.profiles SET level_id = v_next, updated_at = now() WHERE id = r.id;

    -- Enroll in the new level's courses. Old enrollments are kept so past
    -- assignment and quiz results (and the CGPA built from them) stay visible.
    INSERT INTO public.student_enrollments (student_id, course_id)
    SELECT r.id, co.id FROM public.courses co
    WHERE co.class_id = v_next AND co.subject_id = r.department_id
    ON CONFLICT (student_id, course_id) DO NOTHING;

    v_count := v_count + 1;
  END LOOP;

  RETURN v_count;
END;
$$;

REVOKE ALL ON FUNCTION public.promote_students(uuid[]) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.promote_students(uuid[]) TO authenticated;

COMMIT;
